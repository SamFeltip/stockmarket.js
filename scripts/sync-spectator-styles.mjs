import { readFile, writeFile } from "node:fs/promises";

// Keep the large-screen spectator layout aligned with the Android TV display.
const source = await readFile(new URL("../../stockmarket-tv/src/style.css", import.meta.url), "utf8");

const section = (start, end) =>
{
    const first = source.indexOf(start);
    const last = source.indexOf(end, first);
    if (first === -1 || last === -1)
    {
        throw new Error(`Cannot locate TV stylesheet section: ${start}`);
    }

    return source.slice(first, last);
};

const rules = [
    section("button,input{", ".home{"),
    section(".game-screen{", ".code-entry{"),
    section(".connection{", "@media(max-aspect-ratio"),
    section("/* Keep the same proportions", ".demo-next-period{"),
].join("\n").replace(/@keyframes fadeout\{from\{opacity:1\}to\{opacity:0\}\}/, "")
    .replaceAll("Stockmarket Caslon", "Big Caslon")
    .replaceAll("var(--bs-body-bg)", "var(--bs-body-bg, #0f2c12)")
    .replaceAll("var(--bs-primary)", "var(--bs-primary, #fff284)");
const css = `/* Generated by scripts/sync-spectator-styles.mjs from stockmarket-tv/src/style.css. */
@media (min-width: 1000px) {
    html:has(.web-spectator) { font-size: max(9px, min(1.13vw, 1.93vh)); }
    :where(.web-spectator) {
${rules}
        h1#stockmarket-header { font-family: "Big Caslon", serif; }
    }
}
`;

await writeFile(new URL("../src/spectator/tv-display.css", import.meta.url), css);
